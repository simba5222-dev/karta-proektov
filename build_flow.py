    схема = построить()
    файл = Path(__file__).resolve().parent / "export" / "Схема звонков — как есть.json"
    файл.parent.mkdir(parents=True, exist_ok=True)
    схема.сохранить(файл)
    print(f"собрано: {файл}")
    print(f"  блоков {len(схема.блоки)}, стрелок {len(схема.стрелки)}")
