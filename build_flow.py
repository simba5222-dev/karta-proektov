#!/usr/bin/env python3
"""Собрать блок-схему обработки звонков в формате редактора владельца.

Владелец прислал свою схему файлом `.json` и попросил такую же, но со всеми
шагами и человеческим языком — чтобы открыть в том же редакторе и править
прямо там. Поэтому формат повторяется один в один, а не придумывается свой.

Что выяснено про формат опытным путём:

* `x`, `y` у блока — это **центр**, а не левый верхний угол
* разъёмы нумеруются `0` верх, `1` право, `2` низ, `3` лево
* `nodes` — точки ломаной линии, `counts` — по единице на точку
* `x0`, `y0` — положение холста при сохранении

    python3 build_flow.py            собрать в export/
    python3 build_flow.py --mac      заодно положить в Загрузки мака
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

ВЕРХ, ПРАВО, НИЗ, ЛЕВО = 0, 1, 2, 3


class Схема:
    def __init__(self) -> None:
        self.блоки: list[dict] = []
        self.стрелки: list[dict] = []

    def блок(self, x: int, y: int, ш: int, в: int, текст: str,
             тип: str = "Блок", жирный: bool = False) -> int:
        self.блоки.append({
            "x": x, "y": y, "text": текст, "width": ш, "height": в, "type": тип,
            "isMenuBlock": False, "fontSize": 14, "textHeight": 14,
            "isBold": жирный, "isItalic": False, "textAlign": "center",
            "labelsPosition": 1,
        })
        return len(self.блоки) - 1

    def _точка(self, i: int, разъём: int) -> tuple[int, int]:
        b = self.блоки[i]
        x, y, ш, в = b["x"], b["y"], b["width"], b["height"]
        return {ВЕРХ: (x, y - в // 2), ПРАВО: (x + ш // 2, y),
                НИЗ: (x, y + в // 2), ЛЕВО: (x - ш // 2, y)}[разъём]

    def стрелка(self, откуда: int, куда: int, из_: int, в_: int) -> None:
        ax, ay = self._точка(откуда, из_)
        bx, by = self._точка(куда, в_)
        # Ломаная строится по-разному, смотря куда идёт линия: вниз — через
        # горизонтальную перемычку посередине, вбок — через вертикальную.
        if из_ == НИЗ:
            середина = (ay + by) // 2
            узлы = [(ax, ay), (ax, середина), (bx, середина), (bx, by)]
        elif из_ == ПРАВО:
            середина = (ax + bx) // 2
            узлы = [(ax, ay), (середина, ay), (середина, by), (bx, by)]
        else:
            узлы = [(ax, ay), (ax, by), (bx, by)]
        # Точки, совпавшие после округления, убираем: редактор рисует по ним
        # углы, и лишняя точка даёт лишний излом.
        чистые = [узлы[0]]
        for т in узлы[1:]:
            if т != чистые[-1]:
                чистые.append(т)
        self.стрелки.append({
            "startIndex": откуда, "endIndex": куда,
            "startConnectorIndex": из_, "endConnectorIndex": в_,
            "nodes": [{"x": x, "y": y} for x, y in чистые],
            "counts": [1] * len(чистые),
        })

    def сохранить(self, путь: Path) -> None:
        путь.write_text(json.dumps(
            {"blocks": self.блоки, "arrows": self.стрелки, "x0": 60, "y0": 40},
            ensure_ascii=False, indent=1), encoding="utf-8")


def построить() -> Схема:
    с = Схема()
    X = 760          # главный столбец
    СБОКУ = 1620     # куда уходят тупиковые ветки
    К, У, Б = "Начало / конец", "Условие", "Блок"

    начало = с.блок(X, 70, 300, 80, "Кто-то звонит в компанию", К, жирный=True)

    сообщили = с.блок(X, 220, 480, 90,
        "Телефония тут же сообщает нам:\nкто звонил, кому, сколько говорили,\nи даёт ссылку на запись")

    длина = с.блок(X, 400, 420, 150,
        "Разговор вообще состоялся\nи длился дольше 10 секунд?", У)
    короткий = с.блок(СБОКУ, 400, 340, 120,
        "Нет — значит не дозвонились\nили сразу положили трубку.\nНичего не делаем", К)

    реклама = с.блок(X, 620, 420, 150,
        "Клиент позвонил на рекламный номер?\n(«Авито СПБ», «Сайт МСК» и другие)", У)
    ветка_реклама = с.блок(СБОКУ, 640, 620, 300,
        "ДА — это человек по объявлению,\nему почти наверняка нужна техника.\n\n"
        "Слушаем разговор целиком, распознаём,\nразбираем и складываем в заявку:\n"
        "о чём говорили, какая техника нужна,\nадрес объекта, что посоветовать РОПу\n"
        "и что менеджеру, оценка разговора.\n\n"
        "Эту ветку ведёт питерский сервер", Б)

    продажи = с.блок(X, 870, 460, 160,
        "Звонок пришёл менеджеру отдела продаж\nна его прямой номер?", У)
    не_продажи = с.блок(СБОКУ, 900, 380, 150,
        "Нет — это кадры, механизация,\nснабжение или склад.\nИх звонки мы не слушаем", К)

    перезвон = с.блок(X, 1110, 500, 170,
        "А не мы ли сами звонили на этот номер\nдва раза за полчаса до этого?", У)
    это_перезвон = с.блок(СБОКУ, 1110, 460, 190,
        "ДА — значит это исполнитель\nперезванивает узнать,\nзачем его искали.\n\n"
        "Заявки тут быть не может.\nДаже не слушаем — экономим", К)

    есть_заявка = с.блок(X, 1360, 480, 170,
        "У этого клиента уже есть\nоткрытая заявка?", У)
    работают = с.блок(СБОКУ, 1360, 440, 170,
        "ДА — менеджер с ним прямо сейчас\nработает и точно не забудет.\n"
        "Скорее всего звонок про\n«где моя техника»", К)

    слушаем = с.блок(X, 1620, 620, 210,
        "СЛУШАЕМ ПЕРВУЮ МИНУТУ РАЗГОВОРА\n\n"
        "Запись двухканальная: в одном канале\nнаш менеджер, в другом клиент.\n"
        "Распознаём каждого отдельно —\nполучается разговор с именами:\n"
        "кто что сказал", Б, жирный=True)

    спросил = с.блок(X, 1900, 560, 200,
        "ГЛАВНЫЙ ВОПРОС:\nэто КЛИЕНТ спрашивал у МЕНЕДЖЕРА\nпро свободную технику, цену или сроки?", У)
    наоборот = с.блок(СБОКУ, 1900, 520, 230,
        "НЕТ — спрашивал менеджер.\n\nЗначит это мы сами искали технику\n"
        "у подрядчика. Или разговор\nбыл про оплату, документы,\n"
        "текущую аренду.\n\nЗаявки нет", К)

    заводим = с.блок(X, 2180, 660, 210,
        "ЗАВОДИМ ЗАЯВКУ В CRM\n«Пойманная с прослушки»\n\n"
        "Клиент — тот, кто звонил.\nСоисполнитель — менеджер,\nкоторый с ним говорил.\n"
        "Ответственный — служебная учётка", Б, жирный=True)

    что_внутри = с.блок(X, 2470, 700, 250,
        "ЧТО КЛАДЁМ В ЗАЯВКУ\n\n"
        "· весь разговор словами\n"
        "· короткую выжимку: что просил клиент\n"
        "· какая техника и на какой объект\n"
        "· что посоветовать РОПу\n"
        "· что посоветовать менеджеру\n"
        "· оценку разговора от 1 до 5\n"
        "· цитату из записи", К)

    for a, b, из_, в_ in (
        (начало, сообщили, НИЗ, ВЕРХ),
        (сообщили, длина, НИЗ, ВЕРХ),
        (длина, короткий, ПРАВО, ЛЕВО),
        (длина, реклама, НИЗ, ВЕРХ),
        (реклама, ветка_реклама, ПРАВО, ЛЕВО),
        (реклама, продажи, НИЗ, ВЕРХ),
        (продажи, не_продажи, ПРАВО, ЛЕВО),
        (продажи, перезвон, НИЗ, ВЕРХ),
        (перезвон, это_перезвон, ПРАВО, ЛЕВО),
        (перезвон, есть_заявка, НИЗ, ВЕРХ),
        (есть_заявка, работают, ПРАВО, ЛЕВО),
        (есть_заявка, слушаем, НИЗ, ВЕРХ),
        (слушаем, спросил, НИЗ, ВЕРХ),
        (спросил, наоборот, ПРАВО, ЛЕВО),
        (спросил, заводим, НИЗ, ВЕРХ),
        (заводим, что_внутри, НИЗ, ВЕРХ),
    ):
        с.стрелка(a, b, из_, в_)

    # Две другие ветки — отдельной колонкой, они живут своей жизнью.
    П = 2700
    п1 = с.блок(П, 220, 460, 110,
        "ДРУГАЯ ВЕТКА:\nменеджер сам звонит клиенту\n(тёплый прозвон)", К, жирный=True)
    п2 = с.блок(П, 470, 620, 250,
        "Слушаем разговор целиком и сверяем\nс карточкой клиента в CRM:\n\n"
        "· что клиент сказал, а менеджер\n  не записал — с цитатой\n"
        "· какие обязательные вопросы\n  по этой технике не задал\n"
        "· что не предложил в дополнение", Б)
    п3 = с.блок(П, 740, 520, 130,
        "Показываем в отчёте по менеджеру.\nВ CRM пишем, только если\nпо звонку завели заявку", К)

    и1 = с.блок(П, 1100, 460, 110,
        "ТРЕТЬЯ ВЕТКА:\nподборщик звонит поставщику\nискать технику", К, жирный=True)
    и2 = с.блок(П, 1330, 620, 210,
        "Слушаем и ищем: не назвал ли поставщик\nтехнику СВЕРХ той, о которой спрашивали.\n\n"
        "Если назвал — проверяем,\nесть ли она в его карточке", Б)
    и3 = с.блок(П, 1580, 520, 140,
        "Ставим отметку:\n«всё занесено» или «не занесено».\n"
        "Пока считаем, но в CRM не пишем —\nждём решения владельца", К)

    for a, b in ((п1, п2), (п2, п3), (и1, и2), (и2, и3)):
        с.стрелка(a, b, НИЗ, ВЕРХ)
    return с


if __name__ == "__main__":
    п = argparse.ArgumentParser(description=__doc__)
    п.add_argument("--mac", action="store_true", help="Положить и в Загрузки мака.")
    args = п.parse_args()
    схема = построить()
    файл = Path(__file__).resolve().parent / "export" / "Схема звонков — как есть.json"
    файл.parent.mkdir(parents=True, exist_ok=True)
    схема.сохранить(файл)
    print(f"собрано: {файл}")
    print(f"  блоков {len(схема.блоки)}, стрелок {len(схема.стрелки)}")
    if args.mac:
        цель = Path("/home/agent/mac/Downloads") / файл.name
        shutil.copy(файл, цель)
        print(f"положено в Загрузки: {цель.name}")
